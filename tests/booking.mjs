import assert from 'node:assert/strict';
import {addMinutes,bookingProblem,matchesPatient} from '../frontend/src/booking.mjs';
assert.equal(addMinutes('14:35',45),'15:20');
assert.equal(addMinutes('23:45',30),'');
assert.equal(addMinutes('24:00',30),'');
assert.equal(addMinutes('12:10',1.5),'');
assert.equal(matchesPatient({name:'Олена',phone:'+380 (67) 123-45-67'},'380 67'),true);
assert.equal(matchesPatient({name:'Олена'},'олена'),true);
assert.equal(matchesPatient({name:'Олена'},'---'),false);
const form={patient_ids:[1],psychologist_id:3,room_id:2,date:'2026-10-15',start:'14:35',duration:45};
const policy={opening_time:'08:00',closing_time:'18:00',working_days:'12345'};
assert.equal(bookingProblem(form,policy),'');
assert(bookingProblem({...form,date:'2026-02-31'},policy));
assert(bookingProblem({...form,date:'2026-10-17'},policy));
assert(bookingProblem({...form,start:'17:30'},policy));
assert(bookingProblem({...form,patient_ids:[]},policy));
assert(bookingProblem({...form,duration:0},policy));
assert(bookingProblem({...form,duration:45.5},policy));
console.log('PASS: arbitrary minute scheduling, end-time and workday limits, real calendar dates and normalized patient search');
