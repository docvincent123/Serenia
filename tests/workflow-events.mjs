import assert from 'node:assert/strict';
import {feedbackFor,incomingWorkflow,mergeWorkflow} from '../frontend/src/workflow-events.mjs';
import {tvChanges} from '../frontend/src/tv/model.mjs';
const created={id:7,kind:'appointment.created',actor_id:2},arrived={id:8,kind:'patient.arrived',actor_id:3};
assert.equal(feedbackFor('GET','/api/appointments'),null);
assert.equal(feedbackFor('POST','/api/appointments',{}).title,'Запис створено');
assert.equal(feedbackFor('POST','/api/consultations').title,'Консультацію завершено');
assert.equal(feedbackFor('POST','/api/patients/5/draft'),null,'Autosaved drafts do not produce intrusive success messages');
assert.equal(incomingWorkflow({events:[created],cursor:7},null,3).alert.length,0,'Initial history is not a new notification');
assert.deepEqual(incomingWorkflow({events:[created,arrived],cursor:8},6,3).alert,[created],'The actor receives local feedback, not a second remote alert');
assert.equal(incomingWorkflow({events:[created],cursor:7,initial:true},100,3).alert.length,0,'Restored databases reset the cursor without replaying sound');
assert.equal(incomingWorkflow([],7,3),null);
assert.equal(incomingWorkflow({events:[created],cursor:7},7,3).alert.length,0,'Repeated batches do not replay sound');
assert.deepEqual(mergeWorkflow([created],[created,arrived]).map(e=>e.id),[8,7]);
const row={appointment_id:1,patient_id:1,state:'scheduled',called_at:0};
const snapshot=entries=>({date:'2026-10-26',entries});
assert.deepEqual(tvChanges(null,snapshot([row])),[]);
assert.equal(tvChanges(snapshot([]),snapshot([row]))[0].kind,'new');
assert.equal(tvChanges(snapshot([row]),snapshot([{...row,state:'waiting'}]))[0].kind,'arrival');
assert.equal(tvChanges(snapshot([row]),snapshot([{...row,state:'called',called_at:100}]))[0].kind,'call');
assert.deepEqual(tvChanges(snapshot([row]),snapshot([row])),[]);
assert.deepEqual(tvChanges(snapshot([row]),snapshot([])),[],'Completion/removal is not a new call');
console.log('PASS: action feedback, scoped deduplication, history/cursor resets and TV new/arrival/call transitions');
