// Regenerate the embedded native PNG assets from the editable SVG sources.
// Requires sharp (available in the primary runtime, or install in a temporary tool directory).
const fs = require('node:fs');
const path = require('node:path');
const sharp = require(process.env.LEMVORI_SHARP_MODULE || 'sharp');
(async () => {
  const root = path.resolve(__dirname, '../native/linux');
  const uri = async (file, width) => 'data:image/png;base64,' + (await sharp(file).resize({width}).png().toBuffer()).toString('base64');
  const icons = {};
  for (const file of fs.readdirSync(path.join(root, 'icons')).filter(f => f.endsWith('.svg')).sort())
    icons[file.slice(0, -4)] = await uri(path.join(root, 'icons', file), 72);
  const brand = await uri(path.join(root, 'care-brand.svg'), 192);
  const hero = await uri(path.join(root, 'medical-hero.svg'), 2400);
  fs.writeFileSync(path.join(root, 'CareVisuals.js'), '// Generated by tools/build-native-visuals.cjs; SVG sources are editable.\n.pragma library\nvar icons = ' + JSON.stringify(icons) + ';\nvar brand = ' + JSON.stringify(brand) + ';\nvar hero = ' + JSON.stringify(hero) + ';\n');
})();
